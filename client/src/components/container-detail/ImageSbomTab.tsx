'use client'

import { useState, useEffect, useCallback } from 'react'
import { RefreshCw, FileText, Eye, Download } from 'lucide-react'
import { ErrorBlock, LoadingBlock } from '@/components/ui'
import { formatDate, formatImageTag } from '@/utils/formatters'
import { sbomDocumentUrl } from '@/lib/sbom'
import type { ImageSbomTabProps, SbomItem } from './types'

/**
 * The image's SBOM — singular.
 *
 * This tab used to be "SBOM History", a timeline of every SBOM uploaded to a
 * project. A digest is content-addressed, so its component list cannot change:
 * there is exactly one SBOM per image and there is no history to draw. What
 * *does* change is which image a container references, and that is the
 * Deployments tab.
 */
export function ImageSbomTab({ containerId }: ImageSbomTabProps) {
    const [sbom, setSbom] = useState<SbomItem | null>(null)
    const [isLoading, setIsLoading] = useState(true)
    const [error, setError] = useState<string | null>(null)

    const fetchSbom = useCallback(async () => {
        setIsLoading(true)
        setError(null)

        try {
            const response = await fetch(`/api/containers/${containerId}/sboms`)
            if (!response.ok) {
                throw new Error('Failed to fetch the SBOM')
            }
            // A list of at most one: an unscanned image is an empty array
            // rather than a 404 the caller has to special-case.
            const data: SbomItem[] = await response.json()
            setSbom(data[0] ?? null)
        } catch (err) {
            setError(err instanceof Error ? err.message : 'Failed to fetch the SBOM')
        } finally {
            setIsLoading(false)
        }
    }, [containerId])

    useEffect(() => {
        fetchSbom()
    }, [fetchSbom])

    if (isLoading) {
        return (
            <LoadingBlock label="Loading SBOM..." />
        )
    }

    if (error) {
        return (
            <ErrorBlock
                title="Failed to load the SBOM"
                message={error}
                icon={
                    <svg className="size-6 text-danger" fill="none" viewBox="0 0 24 24" strokeWidth="1.5" stroke="currentColor">
                        <path strokeLinecap="round" strokeLinejoin="round" d="M12 9v3.75m9-.75a9 9 0 1 1-18 0 9 9 0 0 1 18 0Zm-9 3.75h.008v.008H12v-.008Z" />
                    </svg>
                }
                onRetry={fetchSbom}
            />
        )
    }

    if (!sbom) {
        return (
            <div className="py-12 text-center">
                <FileText className="mx-auto size-12 text-ink-faint/70" />
                <h3 className="mt-2 text-sm font-semibold text-ink">No SBOM for this image yet</h3>
                <p className="mt-1 text-sm text-ink-muted">
                    The scanner pulls the image and runs syft before an SBOM exists — expect it
                    shortly after the container first appears.
                </p>
            </div>
        )
    }

    const rows: { label: string; value: string; mono?: boolean }[] = [
        { label: 'Image', value: formatImageTag(sbom.imageTag, null) ?? sbom.imageRef, mono: true },
        { label: 'Reference', value: sbom.imageRef, mono: true },
        { label: 'Components', value: String(sbom.componentCount) },
        { label: 'Generated by', value: [sbom.toolName, sbom.toolVersion].filter(Boolean).join(' ') || '—' },
        { label: 'Source', value: sbom.sourceName ?? '—' },
        { label: 'CycloneDX', value: sbom.specVersion },
        { label: 'Scanned', value: formatDate(sbom.createdAt) },
    ]

    return (
        <div className="max-w-2xl">
            <div className="mb-4 flex flex-wrap items-center justify-between gap-2">
                <p className="text-sm text-ink-muted">
                    One SBOM per image — this digest is scanned once for the whole fleet.
                </p>
                <button
                    onClick={fetchSbom}
                    className="inline-flex cursor-pointer items-center gap-1.5 text-sm text-ink-secondary hover:text-ink"
                >
                    <RefreshCw className="size-4" />
                    Refresh
                </button>
            </div>

            <dl className="divide-y divide-edge rounded-md border border-edge bg-surface-raised">
                {rows.map(row => (
                    <div key={row.label} className="flex items-start gap-4 px-3 py-3 sm:px-4">
                        <dt className="w-24 shrink-0 text-sm text-ink-muted sm:w-32">{row.label}</dt>
                        <dd className={`min-w-0 flex-1 break-all text-sm text-ink ${row.mono ? 'font-mono text-xs' : ''}`}>
                            {row.value}
                        </dd>
                    </div>
                ))}
            </dl>

            {/* The document itself — the "saved SBOM" the pricing page sells.
                Current only: one SBOM per image, and a replacement upload
                deletes its predecessor rather than archiving it, so there is
                no older version to offer. Both links go through the BFF; the
                download one carries the server's Content-Disposition. */}
            <div className="mt-4 flex flex-wrap items-center gap-4">
                <a
                    href={sbomDocumentUrl(sbom.id, { download: true })}
                    className="inline-flex items-center gap-1 text-sm text-accent hover:underline"
                >
                    <Download aria-hidden="true" className="size-4" />
                    Download CycloneDX
                </a>
                <a
                    href={sbomDocumentUrl(sbom.id)}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="inline-flex items-center gap-1 text-sm text-accent hover:underline"
                >
                    <Eye aria-hidden="true" className="size-4" />
                    View
                </a>
            </div>
        </div>
    )
}
